import {spawn} from 'node:child_process';
import {mkdtemp,readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createPreview} from '../scripts/preview.mjs';
const {server,url}=await createPreview();
const profile=await mkdtemp(path.join(tmpdir(),'betterframe-chrome-'));
const chrome=spawn(process.env.CHROME??'google-chrome',['--headless=new','--no-sandbox','--disable-gpu','--remote-debugging-port=0','--remote-allow-origins=*',`--user-data-dir=${profile}`,'about:blank'],{stdio:'ignore'});
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let ws;
try{
 let port;
 for(let n=0;n<80;n++){try{port=Number((await readFile(path.join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0]);break;}catch{await sleep(100);}}
 if(!port)throw new Error('Chrome failed to start');
 const tabs=await(await fetch(`http://127.0.0.1:${port}/json/list`)).json();
 ws=new WebSocket(tabs.find(tab=>tab.type==='page').webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
 let id=0;const pending=new Map(),exceptions=[];
 ws.onmessage=event=>{const message=JSON.parse(event.data);if(message.method==='Runtime.exceptionThrown')exceptions.push(message.params);if(message.id){const task=pending.get(message.id);pending.delete(message.id);if(message.error)task.reject(new Error(JSON.stringify(message.error)));else task.resolve(message.result);}};
 const send=(method,params={})=>new Promise((resolve,reject)=>{const n=++id;pending.set(n,{resolve,reject});ws.send(JSON.stringify({id:n,method,params}));});
 const evaluate=async expression=>{const value=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(value.exceptionDetails)throw new Error(JSON.stringify(value.exceptionDetails));return value.result?.value;};
 const waitFor=async expression=>{for(let n=0;n<100;n++){if(await evaluate(expression))return;await sleep(50);}throw new Error('Timed out: '+expression);};
 const click=async label=>{await evaluate(`(()=>{const button=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(label)});if(!button)throw new Error('Missing button');button.click();})()`);};
 const language=async label=>{await evaluate("document.querySelector('.framely-select>button').click()");await waitFor("!!document.querySelector('[role=option]')");await click(label);await waitFor("!document.querySelector('[role=listbox]')");await sleep(300);};
 const screenshot=async name=>{await mkdir('build/screenshots',{recursive:true});const shot=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});await writeFile(`build/screenshots/${name}.png`,Buffer.from(shot.data,'base64'));};
 await send('Page.enable');await send('Runtime.enable');
 await send('Emulation.setDeviceMetricsOverride',{width:1100,height:1200,deviceScaleFactor:1,mobile:false});
 await send('Page.navigate',{url});
 await waitFor("document.documentElement.lang==='zh-CN'&&!!document.querySelector('input[type=range]')");
 await screenshot('quality-zh');
 await language('日本語');
 await waitFor("document.documentElement.lang==='ja'");
 assert.ok((await evaluate('document.body.innerText')).includes('シャープの量'));
 await screenshot('quality-ja');
 await language('English');
 await waitFor("document.documentElement.lang==='en'");
 assert.ok((await evaluate('document.body.innerText')).includes('Sharpen amount'));
 await screenshot('quality-en');
 await evaluate("window.__mock.language('zh-CN')");await sleep(100);
 assert.equal(await evaluate('document.documentElement.lang'),'en','Explicit language must ignore host changes');
 await language('Follow Framely');await waitFor("document.documentElement.lang==='zh-CN'");
 await evaluate("window.__mock.language('en-US')");await waitFor("document.documentElement.lang==='en'");
 await evaluate("document.querySelector('input[role=switch]').click()");await waitFor("window.__mock.state.settings.enabled===true");
 await waitFor("document.body.innerText.includes('Restart SteamVR when convenient')");
 // Native range setter is required for React's input tracking.
 await evaluate(`(()=>{const input=document.querySelector('input[type=range]');const setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set;for(const value of ['0.5','0.75','0.95']){setter.call(input,value);input.dispatchEvent(new Event('input',{bubbles:true}));}})()`);
 await waitFor("window.__mock.state.settings.sharpenAmount===0.95");
 await click('Gentle');await waitFor("window.__mock.state.settings.sharpenAmount===0.6");
 await click('Experimental');await waitFor("document.body.innerText.includes('image corruption')");
 await screenshot('experimental-en');
 await click('SteamVR');await click('Read current settings');await waitFor("!!window.__mock.state.gaze");
 await waitFor("[...document.querySelectorAll('input[role=switch]')].length===5");
 await evaluate("document.querySelectorAll('input[role=switch]')[3].click()");await waitFor("window.__mock.state.gazeModified");
 await click('Restore original SteamVR settings');await waitFor("!window.__mock.state.gazeModified");
 await click('Status & help');await click('Import standalone settings');await waitFor("window.__mock.state.settings.sharpenAmount===0.9");
 await click('Image quality');
 await evaluate("window.__mock.failure='invalid_settings'");await click('Strong');
 await waitFor("!!document.querySelector('[role=alert]')");
 assert.ok((await evaluate("document.querySelector('[role=alert]').textContent")).includes('Invalid setting'));
 await evaluate("window.__mock.failure='';window.__mock.state.loaded=true;window.__mock.state.stats={gpuMsAvg:.98,gpuMsMax:1.22,cpuUsAvg:47,cpuUsMax:60,fps:144,gapMsP99:7.1}");
 await click('Refresh');await waitFor("document.body.innerText.includes('0.98')");
 await send('Emulation.setDeviceMetricsOverride',{width:430,height:1000,deviceScaleFactor:1,mobile:false});
 await sleep(100);
 assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Narrow page must not overflow horizontally');
 await screenshot('quality-narrow');
 assert.deepEqual(exceptions,[],'No uncaught browser errors');
 console.log('Browser smoke passed: all three locales, host-language events, explicit override, live slider updates, presets, restart notice, gaze controls, import, translated errors, stats and narrow layout.');
}finally{
 ws?.close();chrome.kill();server.close();
 await new Promise(resolve=>chrome.once('exit',resolve));
 await rm(profile,{recursive:true,force:true});
}
